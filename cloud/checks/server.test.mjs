import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { readFileSync } from 'node:fs';
import { boot,call,card,entry,ffmpeg,fmt,login,pair,tmp,tone } from './fixtures.mjs';

const cli=fileURLToPath(new URL('../cli.mjs',import.meta.url));
const upload=(site,bearer,data)=>call(site,'/api/cards',{method:'PUT',bearer,data});
const review=(site,cookie)=>call(site,'/api/today',{cookie});
const score=(site,cookie,ticket,outcome='heard',event=randomUUID())=>call(site,'/api/score',{cookie,data:{event,ticket,outcome}});

test('authenticated atomic publishing, restart and retry, correction, withdrawals and text imports',async t=>{
  const path=join(tmp(),'review.sqlite');
  let ms=fmt('2026-11-25');
  let site=await boot(path,{now:()=>ms,sessionMs:90000});
  t.after(()=>site.close());
  const pairTime=ms;
  const bearer=await pair(site,pairTime), cookie=await login(site);
  const sound=tone(), data=card(sound), {card:c}=data;
  assert.equal((await upload(site,null,data)).status,401);
  assert.equal((await call(site,'/api/today',{bearer})).status,401);
  assert.equal((await upload(site,bearer,{...data,media:[]})).status,422);
  assert.equal((await review(site,cookie)).body.items.length,0);
  const silent=card(tone('anullsrc=r=44100:d=0.4'));
  const tooLong=card(tone('sine=duration=31'));
  assert.equal((await upload(site,bearer,silent)).body.error,'bad-audio');
  assert.equal((await upload(site,bearer,tooLong)).body.error,'bad-audio');
  const edgePath=join(tmp(),'exactly-30.mp3');
  ffmpeg('-f','lavfi','-i','sine=duration=30','-b:a','96k','-c:a','libmp3lame','-id3v2_version','0','-n',edgePath);
  const edge=card(readFileSync(edgePath));
  assert.equal((await upload(site,bearer,edge)).status,200);
  assert.equal((await upload(site,bearer,{card:{...edge.card,status:'withdrawn',revision:2,examples:[]},media:[]})).status,200);
  assert.equal((await upload(site,bearer,data)).body.result,'ready');
  const first=(await review(site,cookie)).body.items[0];
  assert.equal((await call(site,first.audio)).status,401);
  assert.equal((await call(site,first.audio,{bearer})).status,401);
  assert.deepEqual((await call(site,first.audio,{cookie})).body,sound);
  assert.equal((await call(site,first.audio,{cookie})).headers.get('content-disposition'),'inline');
  const range=await call(site,first.audio,{cookie,headers:{Range:'bytes=2-9'}});
  assert.equal(range.status,206); assert.deepEqual(range.body,sound.subarray(2,10));
  await site.close();
  site=await boot(path,{now:()=>ms,sessionMs:90000,password:site.password},site.port);
  assert.equal((await upload(site,bearer,data)).body.result,'ready');
  assert.equal((await review(site,cookie)).body.items.length,1);
  assert.equal((await upload(site,bearer,{...data,card:{...c,meaning:'同版本冲突'}})).status,409);
  const v2={...data,card:{...c,revision:2,meaning:'失约'}};
  assert.equal((await upload(site,bearer,{...v2,media:[]})).status,422);
  assert.equal((await review(site,cookie)).body.items[0].meaning,'放鸽子');
  assert.equal((await upload(site,bearer,v2)).body.result,'ready');
  assert.equal((await score(site,cookie,first.id)).body.result,'changed');
  const fixed=(await review(site,cookie)).body.items[0];
  assert.equal(fixed.meaning,'失约');
  const text={card:{...c,cardId:randomUUID(),status:'text',count:0,reason:'import',meaning:'',english:'external text',examples:[]},media:[]};
  assert.equal((await upload(site,bearer,text)).status,200);
  assert.equal((await upload(site,bearer,text)).status,200);
  assert.equal((await review(site,cookie)).body.items.length,1);
  assert.equal((await call(site,'/api/library',{cookie})).body.filter(x=>x.textOnly).length,1);
  assert.equal((await upload(site,bearer,{card:{...c,status:'withdrawn',revision:3,examples:[]},media:[]})).status,200);
  assert.equal((await upload(site,bearer,data)).body.result,'superseded');
  assert.equal((await review(site,cookie)).body.items.length,0);
  assert.equal((await score(site,cookie,fixed.id)).body.result,'withdrawn');
  assert.equal((await call(site,fixed.audio,{cookie})).status,404);
  const other=await login(site);
  assert.equal((await call(site,'/api/logout',{cookie,data:{},origin:'https://outside.invalid'})).status,403);
  assert.equal((await call(site,'/api/logout',{cookie,data:{}})).status,200);
  assert.equal((await call(site,fixed.audio,{cookie})).status,401);
  ms+=91000;
  assert.equal((await call(site,fixed.audio,{cookie:other})).status,401);
  site.store.revokeDevice('test');
  assert.equal((await upload(site,bearer,data)).status,401);
});

test('shared daily scores, rotating examples, 1/3/7, late offline day, backup and clean restore',async t=>{
  const base=tmp(), path=join(base,'live.sqlite'), backup=join(base,'copy.sqlite'), restored=join(base,'restored.sqlite');
  let ms=fmt('2026-11-25');
  const site=await boot(path,{now:()=>ms});
  t.after(()=>site.close());
  const a=await login(site), b=await login(site), bearer=await pair(site,ms), sound=tone();
  const data=card(sound,'bail on',undefined,[entry(sound,'bail on','You always bail on them.')]);
  assert.equal((await upload(site,bearer,data)).status,200);
  const first=(await review(site,a)).body;
  assert.equal(first.day,'2026-11-25');
  const ticket=first.items[0].id, id=randomUUID();
  const results=await Promise.all([score(site,a,ticket,'heard',id),score(site,b,ticket,'heard')]);
  assert.deepEqual(results.map(r=>r.body.result).sort(),['accepted','already-scored']);
  const accepted=results.find(r=>r.body.result==='accepted').body;
  assert.equal(accepted.due,'2026-11-26');
  assert.equal((await review(site,b)).body.items.length,0);
  assert.deepEqual((await score(site,a,ticket,'heard',id)).body,results[0].body);
  assert.equal((await score(site,a,ticket,'hint',id)).status,409);
  ms=fmt('2026-11-26');
  const second=(await review(site,b)).body.items[0];
  assert.notEqual(second.english,first.items[0].english);
  assert.equal((await score(site,b,second.id)).body.due,'2026-11-29');
  ms=fmt('2026-11-29');
  const day3=(await review(site,a)).body.items[0];
  assert.equal((await score(site,a,day3.id)).body.due,'2026-12-06');
  ms=fmt('2026-12-06');
  const earlier=(await review(site,a)).body.items[0];
  ms=fmt('2026-12-07');
  const later=(await review(site,b)).body.items[0];
  assert.equal((await score(site,b,later.id,'hint')).body.due,'2026-12-08');
  const late=(await score(site,a,earlier.id,'heard')).body;
  assert.equal(late.day,'2026-12-06'); assert.equal(late.due,'2026-12-08');
  const v2={...data,card:{...data.card,revision:2,meaning:'爽约'}};
  assert.equal((await upload(site,bearer,v2)).status,200);
  assert.equal((await call(site,'/api/library',{cookie:a})).body[0].due,'2026-12-08');
  const execute=(db,...args)=>{
    const r=spawnSync(process.execPath,[cli,...args],{env:{...process.env,REVIEW_DB:db},encoding:'utf8'});
    assert.equal(r.status,0,r.stderr);
  };
  execute(path,'backup',backup); execute(restored,'restore',backup);
  ms=fmt('2026-12-08');
  const copy=await boot(restored,{now:()=>ms,password:site.password}); t.after(()=>copy.close());
  assert.equal((await review(copy,a)).status,401);
  const fresh=await login(copy), restoredCard=(await review(copy,fresh)).body.items[0];
  assert.equal(restoredCard.meaning,'爽约');
  assert.deepEqual((await call(copy,restoredCard.audio,{cookie:fresh})).body,sound);
  for(const table of ['cards','audio','scores']) {
    const query=table==='audio'?'SELECT key,id,digest FROM audio ORDER BY key,id':`SELECT * FROM ${table} ORDER BY 1`;
    assert.deepEqual(copy.store.db.prepare(query).all(),site.store.db.prepare(query).all());
  }
  assert.equal((await score(copy,fresh,restoredCard.id)).body.due,'2026-12-09');
});
